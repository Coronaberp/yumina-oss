import type { EmbeddingProfile, MemoryDatabase, MemoryScope } from "./types.js";
export function validateDimensions(dim: number): number {
  if (!Number.isInteger(dim) || dim < 1 || dim > 16000)
    throw new Error("Invalid embedding dimensions");
  return dim;
}
export function quoteSchema(schema: string): string {
  if (!/^shm_[a-f0-9]{32}$/.test(schema))
    throw new Error("Invalid generated memory schema");
  return `"${schema}"`;
}
export async function ensureRegistry(db: MemoryDatabase): Promise<void> {
  await db.query("CREATE EXTENSION IF NOT EXISTS vector");
  await db.query("CREATE SCHEMA IF NOT EXISTS memory_registry");
  await db.query(
    `CREATE TABLE IF NOT EXISTS memory_registry.profiles(id text PRIMARY KEY,user_id text NOT NULL,schema_name text NOT NULL UNIQUE,base_url text NOT NULL,model text NOT NULL,dimensions integer NOT NULL CHECK(dimensions BETWEEN 1 AND 16000),send_dimensions boolean NOT NULL DEFAULT false,status text NOT NULL CHECK(status IN ('pending','ready','failed')),revision integer NOT NULL,active boolean NOT NULL DEFAULT false,credential text,error_code text,created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now())`,
  );
  await db.query(
    "CREATE TABLE IF NOT EXISTS memory_registry.profile_owners(user_id text PRIMARY KEY,next_revision integer NOT NULL DEFAULT 0,deleted boolean NOT NULL DEFAULT false)",
  );
  // Retain provenance if a shared source is withdrawn; it must never become a
  // personal override merely because its source no longer exists.
  await db.query("ALTER TABLE memory_registry.profiles ADD COLUMN IF NOT EXISTS inherited_from text");
  await db.query(
    "ALTER TABLE memory_registry.profile_owners ADD COLUMN IF NOT EXISTS deleted boolean NOT NULL DEFAULT false",
  );
  await db.query(
    "CREATE UNIQUE INDEX IF NOT EXISTS profiles_user_revision ON memory_registry.profiles(user_id,revision)",
  );
  await db.query(
    "CREATE UNIQUE INDEX IF NOT EXISTS profiles_active_user ON memory_registry.profiles(user_id) WHERE active",
  );
}
export async function ensureProfileSchema(
  db: MemoryDatabase,
  profile: EmbeddingProfile,
): Promise<void> {
  const s = quoteSchema(profile.schemaName),
    d = validateDimensions(profile.dimensions);
  await db.transaction(async (tx) => {
    // Match owner purge's owner-before-profile lock order and retain both locks
    // until DDL commits, so a purged profile cannot recreate its schema.
    const owner = await tx.query<{ deleted: boolean }>(
      "SELECT deleted FROM memory_registry.profile_owners WHERE user_id=$1 FOR UPDATE",
      [profile.userId],
    );
    if (!owner.rows.length || owner.rows[0]!.deleted)
      throw new Error("Memory owner deleted");
    const registered = await tx.query(
      "SELECT id FROM memory_registry.profiles WHERE id=$1 AND user_id=$2 AND schema_name=$3 AND dimensions=$4 FOR SHARE",
      [profile.id, profile.userId, profile.schemaName, d],
    );
    if (!registered.rows.length) throw new Error("Unregistered memory profile");
    await tx.query(`CREATE SCHEMA IF NOT EXISTS ${s}`);
    const statements = [
      `users(id text PRIMARY KEY)`,
      `characters(id text PRIMARY KEY,owner_id text REFERENCES ${s}.users(id) ON DELETE SET NULL,apply_global_lore boolean NOT NULL DEFAULT false)`,
      `sessions(id text PRIMARY KEY,user_id text REFERENCES ${s}.users(id) ON DELETE SET NULL,char_id text REFERENCES ${s}.characters(id) ON DELETE RESTRICT,char_doing text,char_location text,known_names text NOT NULL DEFAULT '[]')`,
      `memory_facts(id text PRIMARY KEY,session_id text NOT NULL,char_id text,text text NOT NULL,fact_type text NOT NULL,participants text[] NOT NULL,importance integer NOT NULL,valence integer NOT NULL,reinforcements integer NOT NULL,valid_from_turn integer NOT NULL,valid_until_turn integer,last_turn integer NOT NULL,created_ts bigint NOT NULL,expired_ts bigint,superseded_by text,pinned boolean NOT NULL DEFAULT false,location text,batch_id text,embedding vector(${d}))`,
      `memory_extract_cursors(session_id text PRIMARY KEY,settled_exchanges integer NOT NULL)`,
      `memory_extract_batches(id text PRIMARY KEY,session_id text NOT NULL,pair_start integer NOT NULL,pair_end integer NOT NULL,turn integer NOT NULL,created_ts bigint NOT NULL)`,
      `memory_reinforce_log(seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session_id text NOT NULL,fact_id text NOT NULL,batch_id text NOT NULL,prior_reinforcements integer NOT NULL,prior_last_turn integer NOT NULL,created_ts bigint NOT NULL)`,
      `memory_vectors(id text PRIMARY KEY,session_id text NOT NULL,char_id text,text text NOT NULL,ts bigint NOT NULL,embedding vector(${d}))`,
      `lore(id text PRIMARY KEY,char_id text,owner_id text REFERENCES ${s}.users(id) ON DELETE SET NULL,keys text NOT NULL DEFAULT '',require_keys text NOT NULL DEFAULT '',exclude_keys text NOT NULL DEFAULT '',content text NOT NULL DEFAULT '',always integer NOT NULL DEFAULT 0,image text NOT NULL DEFAULT '',category text NOT NULL DEFAULT '',hidden integer NOT NULL DEFAULT 0,name text NOT NULL DEFAULT '',appearance_tags text NOT NULL DEFAULT '',appearance_tags_negative text NOT NULL DEFAULT '',is_explicit integer NOT NULL DEFAULT 0,usable_as_persona integer NOT NULL DEFAULT 0,gender text NOT NULL DEFAULT 'Female',metadata text NOT NULL DEFAULT '',created double precision NOT NULL,persona_source_char_id text)`,
      `lore_links(id text PRIMARY KEY,lore_id_a text NOT NULL,lore_id_b text NOT NULL,pair_key text GENERATED ALWAYS AS (CASE WHEN lore_id_a<lore_id_b THEN lore_id_a||':'||lore_id_b ELSE lore_id_b||':'||lore_id_a END) STORED,label text NOT NULL DEFAULT '',created double precision NOT NULL,CHECK(lore_id_a<>lore_id_b),UNIQUE(pair_key))`,
      `lore_secrets(id text PRIMARY KEY,lore_id text NOT NULL REFERENCES ${s}.lore(id) ON DELETE CASCADE,text text NOT NULL,position integer NOT NULL,created double precision NOT NULL)`,
      `lore_chunks(id text PRIMARY KEY,lore_id text NOT NULL REFERENCES ${s}.lore(id) ON DELETE CASCADE,part_id integer NOT NULL,content text NOT NULL,created_ts bigint NOT NULL)`,
      `session_secret_reveals(id text PRIMARY KEY,session_id text NOT NULL,secret_id text NOT NULL,revealed double precision NOT NULL,batch_id text,fact_id text,UNIQUE(session_id,secret_id))`,
      `session_lore_state(id text PRIMARY KEY,session_id text NOT NULL REFERENCES ${s}.sessions(id) ON DELETE CASCADE,lore_id text NOT NULL REFERENCES ${s}.lore(id) ON DELETE CASCADE,override_content text,override_fact_id text,batch_id text,prior_override_content text,prior_override_fact_id text,updated double precision NOT NULL,UNIQUE(session_id,lore_id))`,
      `memory_clusters(id text PRIMARY KEY,session_id text NOT NULL,title text NOT NULL DEFAULT '',summary_text text NOT NULL,created_turn integer NOT NULL,source_batch_ids text NOT NULL,created_at double precision NOT NULL)`,
      `memory_cluster_items(id text PRIMARY KEY,cluster_id text NOT NULL,fact_id text NOT NULL,created_ts bigint NOT NULL,UNIQUE(cluster_id,fact_id))`,
      `lore_vectors(lore_id text NOT NULL,part_id integer NOT NULL DEFAULT 0,char_id text,embedding vector(${d}),PRIMARY KEY(lore_id,part_id))`,
      `secret_vectors(secret_id text PRIMARY KEY,lore_id text NOT NULL,char_id text,embedding vector(${d}))`,
      `cluster_vectors(cluster_id text PRIMARY KEY,session_id text NOT NULL,embedding vector(${d}))`,
    ];
    for (const statement of statements)
      await tx.query(`CREATE TABLE IF NOT EXISTS ${s}.${statement}`);
    for (const table of [
      "memory_facts",
      "memory_extract_batches",
      "memory_reinforce_log",
      "memory_clusters",
    ])
      await tx.query(
        `CREATE INDEX IF NOT EXISTS ${table}_session_idx ON ${s}.${table}(session_id)`,
      );
    for (const [table, column] of [
      ["memory_reinforce_log", "fact_id"],
      ["memory_reinforce_log", "batch_id"],
      ["memory_cluster_items", "cluster_id"],
      ["memory_cluster_items", "fact_id"],
      ["lore", "char_id"],
      ["lore_links", "lore_id_a"],
      ["lore_links", "lore_id_b"],
      ["lore_secrets", "lore_id"],
      ["session_lore_state", "session_id"],
    ])
      await tx.query(
        `CREATE INDEX IF NOT EXISTS ${table}_${column}_idx ON ${s}.${table}(${column})`,
      );
    if (d <= 2000)
      for (const table of [
        "memory_facts",
        "memory_vectors",
        "lore_vectors",
        "secret_vectors",
        "cluster_vectors",
      ])
        await tx.query(
          `CREATE INDEX IF NOT EXISTS ${table}_hnsw ON ${s}.${table} USING hnsw (embedding vector_cosine_ops)`,
        );
  });
}
export async function validateScope(
  db: MemoryDatabase,
  scope: MemoryScope,
): Promise<void> {
  quoteSchema(scope.schemaName);
  const r = await db.query(
    "SELECT id FROM memory_registry.profiles WHERE id=$1 AND user_id=$2 AND schema_name=$3",
    [scope.profileId, scope.ownerUserId, scope.schemaName],
  );
  if (!r.rows.length) throw new Error("Invalid memory owner scope");
  const s = quoteSchema(scope.schemaName);
  const session = await db.query(
    `SELECT id FROM ${s}.sessions WHERE id=$1 AND user_id=$2 AND char_id IS NOT DISTINCT FROM $3`,
    [scope.sessionId, scope.ownerUserId, scope.charId],
  );
  if (!session.rows.length) throw new Error("Invalid memory session scope");
}
export async function ensureIdentity(
  db: MemoryDatabase,
  scope: MemoryScope,
): Promise<void> {
  const s = quoteSchema(scope.schemaName);
  await db.transaction(async (tx) => {
    // Canonical writes share-lock the profile before touching source tables.
    // Reindex and purge acquire their exclusive profile lock first.
    const registered = await tx.query(
      "SELECT id FROM memory_registry.profiles WHERE id=$1 AND user_id=$2 AND schema_name=$3 FOR SHARE",
      [scope.profileId, scope.ownerUserId, scope.schemaName],
    );
    if (!registered.rows.length) throw new Error("Invalid memory owner scope");
    await tx.query(
      `INSERT INTO ${s}.users(id) VALUES($1) ON CONFLICT DO NOTHING`,
      [scope.ownerUserId],
    );
    if (scope.charId)
      await tx.query(
        `INSERT INTO ${s}.characters(id,owner_id) VALUES($1,$2) ON CONFLICT DO NOTHING`,
        [scope.charId, scope.ownerUserId],
      );
    await tx.query(
      `INSERT INTO ${s}.sessions(id,user_id,char_id) VALUES($1,$2,$3) ON CONFLICT DO NOTHING`,
      [scope.sessionId, scope.ownerUserId, scope.charId],
    );
    await validateScope(tx, scope);
  });
}
