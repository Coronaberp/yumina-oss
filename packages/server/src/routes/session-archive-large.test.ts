import "../test/database-fixture.js";
import { test, after, mock } from "node:test";
import assert from "node:assert/strict";
import { openAsBlob } from "node:fs";
import { open, mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { Hono } from "hono";
import { eq } from "drizzle-orm";
import { db } from "../db/index.js";
import { user, worlds, playSessions, messages, assets } from "../db/schema.js";
import { auth } from "../lib/auth.js";
import { STORAGE_DIR } from "../lib/env.js";
import { requestBodyLimit } from "../middleware/request-body-limit.js";
import { sessionArchiveRoutes } from "./session-archives.js";
import { parseArchiveUpload } from "../../../app/src/features/chat/archive-upload.js";
import { importArchivePayload, ARCHIVE_CHUNK_BYTES } from "../../../app/src/features/chat/archive-import-client.js";

after(async () => { mock.restoreAll(); if ("close" in db.$client) await db.$client.close(); });
test("200 MB HTML full save extracts inert JSON, uploads sequential chunks and restores all 107 assets and seven messages", { skip: process.env.YUMINA_ARCHIVE_LARGE_TEST !== "1" }, async () => {
  const owner = crypto.randomUUID(), stamp = "2026-10-13T01:00:00.000Z";
  await db.insert(user).values({ id: owner, name: "Synthetic large import", email: `${owner}@test.invalid`, emailVerified: true });
  const directory = await mkdtemp(join(tmpdir(), "yumina-large-archive-")), path = join(directory, "full-save.html");
  const expected = new Map<string, string>(), hash = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
  const totalDecoded = 156_584_312, count = 107;
  const state = { worldId: "original-world", variables: { hp: 7 }, turnCount: 15, metadata: { saved: "s".repeat(10000) } };
  const definition = { entries: [], variables: [], version: "21.0.0", authoredSource: "a".repeat(720000), media: [] as string[] };
  const messageRows = Array.from({ length: 7 }, (_, i) => ({ id: `source-${i}`, role: i % 2 ? "user" : "assistant", content: `Message ${i} ${"m".repeat(17000)}`, createdAt: stamp }));
  const keys = Array.from({ length: count }, (_, i) => i < 70 ? `@asset:12345678-${i}` : i < 106 ? `/vn-assets/sprite-${i}.png` : "https://old.example/cdn/12345678-font");
  definition.media = keys;
  const archive = { format: "yumina-chat", version: 1, mode: "full-save", exportedAt: stamp, session: { id: "original-session", name: "Large synthetic save", createdAt: stamp, updatedAt: stamp }, world: { id: "original-world", name: "Synthetic academy", description: "Generated byte preservation fixture", schema: definition },
    player: { name: "Saved player", avatar: null }, participants: [], display: [], messages: messageRows,
    restore: { state, persona: { persona: { name: "Saved player" }, started: true }, settings: { sessionMemoryPinned: "Saved continuity" }, checkpoints: [], memories: [], snippets: [], continuityNotes: [] } };
  const file = await open(path, "w");
  try {
    await file.writeFile('<html><script>throw new Error("import must never execute this")</script><script type="application/json" id="yumina-export">' + JSON.stringify(archive).slice(0, -1) + ',"assets":{');
    for (let i = 0; i < count; i++) {
      const bytes = Buffer.alloc(Math.floor(totalDecoded / count) + (i < totalDecoded % count ? 1 : 0), i);
      // Synthetic binary fixtures exercise transport/storage, not image decoding.
      const mime = i < 71 ? "image/webp" : i < 106 ? "image/png" : "font/ttf";
      expected.set(keys[i]!, hash(bytes));
      await file.appendFile((i ? "," : "") + JSON.stringify(keys[i]) + ":" + JSON.stringify(`data:${mime};base64,${bytes.toString("base64")}`));
    }
    await file.appendFile('}}</script></html>');
  } finally { await file.close(); }
  const originalFetch = globalThis.fetch;
  try {
    const html = await openAsBlob(path, { type: "text/html" });
    const upload = await parseArchiveUpload(html);
    assert.equal(upload.preview.mode, "full-save"); assert.equal(upload.preview.messageCount, 7);
    assert.ok(upload.payload.size > 200_000_000);
    mock.method(auth.api, "getSession", async () => ({ user: { id: owner }, session: { id: "large-test", userId: owner, expiresAt: new Date(Date.now() + 60000) } }));
    const app = new Hono(); app.use("*", requestBodyLimit); app.route("/api/session-archives", sessionArchiveRoutes);
    let chunks = 0, completions = 0, uploaded = 0, inFlight = 0;
    globalThis.fetch = async (input, init) => {
      assert.equal(inFlight++, 0, "chunks must remain sequential");
      try {
        const url = String(input);
        if (init?.method === "PUT") { const size = (init.body as Blob).size; assert.ok(size <= ARCHIVE_CHUNK_BYTES); chunks++; uploaded += size; }
        if (url.endsWith("/complete")) completions++;
        return await app.request(url, init);
      } finally { inFlight--; }
    };
    const result = await importArchivePayload(upload.payload, { requestId: upload.requestId });
    assert.equal(uploaded, upload.payload.size); assert.equal(chunks, Math.ceil(upload.payload.size / ARCHIVE_CHUNK_BYTES)); assert.equal(completions, 1);
    const [session] = await db.select().from(playSessions).where(eq(playSessions.id, result.sessionId));
    assert.deepEqual(session!.state, { ...state, worldId: result.worldId });
    assert.equal(session!.sessionMemoryPinned, "Saved continuity"); assert.equal(session!.sessionPersona!.persona!.name, "Saved player");
    const [world] = await db.select().from(worlds).where(eq(worlds.id, result.worldId));
    assert.equal(world!.status, "draft"); assert.equal(world!.schema.authoredSource, definition.authoredSource);
    const savedAssets = await db.select().from(assets).where(eq(assets.worldId, result.worldId)); assert.equal(savedAssets.length, 107);
    assert.equal(savedAssets.reduce((sum, asset) => sum + asset.sizeBytes!, 0), totalDecoded);
    const remaining = new Set(expected.values());
    for (const asset of savedAssets) { const actual = hash(await readFile(join(STORAGE_DIR, asset.url))); assert.ok(remaining.delete(actual)); }
    assert.equal(remaining.size, 0);
    assert.equal((await db.select().from(messages).where(eq(messages.sessionId, result.sessionId))).length, 7);
    assert.deepEqual(await importArchivePayload(upload.payload, { requestId: upload.requestId }), result); assert.equal(completions, 1);
    console.log(JSON.stringify({ htmlBytes: html.size, jsonBytes: upload.payload.size, chunks, assets: savedAssets.length, decodedBytes: totalDecoded, messages: 7, maxRssKiB: process.resourceUsage().maxRSS }));
  } finally { globalThis.fetch = originalFetch; await rm(directory, { recursive: true, force: true }); }
});
