import test from "node:test";
import { readFileSync } from "node:fs";
import { legacyStatusTemplates } from "@yumina/engine";
import assert from "node:assert/strict";
import type { WorldDefinition, RootComponent } from "@yumina/engine";
import { interfaceKey, switchInterface, customUiName, withCurrentBundles } from "./interface-presets";
import { readStatusConfig, writeStatusConfig, initialStatusConfig } from "./status-visualizations";

const root = (name: string, files: Record<string, string>, interfaceId?: string): RootComponent => ({ id: "root", name, files, entryFile: "index.tsx", updatedAt: "old", interfaceId });
const classic = root("Classic", { "index.tsx": "export default function MyWorld(){return <Chat />;}" }, "classic");
test("switching preserves modified UI files, selected mode and story through schema JSON reload", () => {
  const custom = root("My UI", { "index.tsx": "custom", "sprites.ts": "edited sprite config" });
  const original = { name: "Story", rootComponent: custom, variables: [{ id: "affinity" }], installedBundles: [] } as unknown as WorldDefinition;
  const key = interfaceKey(custom);
  const changed = switchInterface(original, "classic", classic);
  assert.deepEqual(changed.variables, original.variables);
  assert.equal(changed.rootComponent!.interfaceId, "classic");
  assert.equal(changed.rootComponent!.files["index.tsx"], classic.files["index.tsx"]);
  const reloaded = JSON.parse(JSON.stringify(changed));
  const restored = switchInterface(reloaded, key, custom);
  assert.deepEqual(restored.rootComponent!.files, custom.files);
  assert.deepEqual(original.rootComponent, custom, "no mutation");
});
test("default VN is recognized without classifying arbitrary custom Chat wrappers as Classic", () => {
  assert.equal(interfaceKey(classic), "classic");
  assert.equal(interfaceKey(root("VN", { "index.tsx": 'return <main className="vn-root" />', "passages.ts": "code", "sprites.ts": "config", "styles.ts": "css" })), "vn");
  assert.notEqual(interfaceKey(root("Other", { "index.tsx": "export default function UI(){ return <Chat renderBubble={myBubble}/>; }" })), "classic");
});
test("names accept long input and truncate at 50 Unicode characters on save", () => {
  assert.equal(customUiName("  " + "😀".repeat(60) + "  "), "😀".repeat(50));
  assert.equal(customUiName("  "), "");
});
test("switching preserves current bundle files and composes only the new user root", () => {
  const current = root("VN", { "index.tsx": "// AUTO-GENERATED by importBundle", "__user-root.tsx": "old", "_bundles/hud/index.tsx": "HUD", "_bundles/hud/data.ts": "DATA" });
  const next = withCurrentBundles(classic, current, folders => "COMPOSER:" + folders.join(","));
  assert.equal(next.files["__user-root.tsx"], classic.files["index.tsx"]);
  assert.equal(next.files["_bundles/hud/data.ts"], "DATA");
  assert.equal(next.files["index.tsx"], "COMPOSER:hud");
});

test("the base VN seeds status from the card's variables and restores edited status when switching back", () => {
  const variables = [{ id: "hp", name: "Health", type: "number" as const, defaultValue: 84, max: 100 }];
  const vn = root("VN", { "index.tsx": "VN", "status-config.ts": writeStatusConfig(initialStatusConfig([])) }, "vn");
  const world = { name: "Story", rootComponent: classic, variables } as WorldDefinition;
  const selected = switchInterface(world, "vn", { ...vn, id: "vn" });
  assert.equal(readStatusConfig(selected.rootComponent!.files["status-config.ts"]).fields[0].variableId, "hp");
  const config = readStatusConfig(selected.rootComponent!.files["status-config.ts"]);
  selected.rootComponent!.files["status-config.ts"] = writeStatusConfig({ ...config, title: "My character" });
  const back = switchInterface(switchInterface(selected, "classic", { ...classic, id: "classic" }), "vn", { ...vn, id: "vn" });
  assert.equal(readStatusConfig(back.rootComponent!.files["status-config.ts"]).title, "My character");
});


test("returning to an older cached VN updates shipped displays and retains its saved configuration", () => {
  const folder = new URL("../../../../../../interfaces/vn/", import.meta.url);
  const templates = Object.fromEntries(["status-data.ts", "status-view.tsx", "status-gauge.tsx", "status-widgets.tsx"].map(name => [name, readFileSync(new URL(name, folder), "utf8")]));
  const config = writeStatusConfig({ ...initialStatusConfig([]), title: "Saved character" });
  const oldVn = root("VN", { ...legacyStatusTemplates, "status-config.ts": config, "sprites.ts": "authored sprite map", "index.tsx": "saved UI" }, "vn");
  const world = { rootComponent: classic, variables: [], interfaceDrafts: { vn: oldVn } } as unknown as WorldDefinition;
  const restored = switchInterface(world, "vn", { ...oldVn, id: "vn", files: templates });
  for (const name of Object.keys(templates)) assert.equal(restored.rootComponent!.files[name], templates[name]);
  assert.equal(restored.rootComponent!.files["status-config.ts"], config);
  assert.equal(restored.rootComponent!.files["sprites.ts"], "authored sprite map");
  assert.equal(restored.rootComponent!.files["index.tsx"], "saved UI");
  assert.equal(oldVn.files["status-view.tsx"], legacyStatusTemplates["status-view.tsx"]);
});
